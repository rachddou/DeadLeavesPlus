"""
Random-mask inpainting training using deepinv physics.

Forward model:  deepinv.physics.Inpainting with per-batch Bernoulli masks
                generated by BernoulliSplittingMaskGenerator.
Network input:  cat([y_or_proxy, mask_1c], dim=1)  — C+1 channels.
TV proxy:       optional Chambolle PGD on GPU; see --use_proxy.
"""

